def _patched(patch: object) -> object:
    """Apply one WEB_SDK_MANIFEST_CASES patch to a copy of MINIMAL.

    A patch that is not a dict replaces the manifest outright. Nested dicts
    merge one level deep, which is as deep as any of the 42 cases reach.
    """
    if not isinstance(patch, dict):
        return copy.deepcopy(patch)
    out = copy.deepcopy(MINIMAL)
    for key, value in patch.items():
        if value is _DELETE:
            out.pop(key, None)
        elif isinstance(value, dict) and isinstance(out.get(key), dict):
            for k, v in value.items():
                if v is _DELETE:
                    out[key].pop(k, None)
                else:
                    out[key][k] = copy.deepcopy(v)
        else:
            out[key] = copy.deepcopy(value)
    return out


