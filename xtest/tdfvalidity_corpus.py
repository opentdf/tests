def corpus() -> list[Case]:
    """Every static case, in a stable order. Raises on a duplicated id."""
    cases = [c for group in GROUPS for c in group()]
    seen: set[str] = set()
    for c in cases:
        if c.id in seen:
            raise ValueError(f"duplicate case id {c.id!r}")
        seen.add(c.id)
    return cases


def digest(cases: Sequence[Case]) -> str:
    """One SHA-256 over every id and its bytes, to show two runs read the same."""
    h = hashlib.sha256()
    for c in cases:
        h.update(c.id.encode() + b"\0")
        h.update(hashlib.sha256(c.data).digest())
    return h.hexdigest()


def write(cases: Sequence[Case], dest: Path) -> dict[str, Path]:
    """Write each case to ``dest/<filename>``; return id -> path."""
    dest.mkdir(parents=True, exist_ok=True)
    paths: dict[str, Path] = {}
    for c in cases:
        p = dest / c.filename
        if not p.is_file() or p.read_bytes() != c.data:
            p.write_bytes(c.data)
        paths[c.id] = p
    return paths


def by_id(cases: Sequence[Case]) -> dict[str, Case]:
    return {c.id: c for c in cases}
