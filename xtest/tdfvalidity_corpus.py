# --- schema/: one keyword at a time -----------------------------------------

#: A value of the wrong JSON type for each type a schema node may allow.
_WRONG_TYPE: list[tuple[str, object]] = [
    ("number", 12345),
    ("string", "x"),
    ("boolean", True),
    ("object", {}),
    ("array", []),
    ("null", None),
]

#: A value that is only of the named JSON type.
_OF_TYPE: dict[str, object] = {
    "string": "s",
    "number": 1.5,
    "boolean": False,
    "object": {},
    "array": [],
    "null": None,
}

Path_ = tuple[str | int, ...]


def _json_type(value: object) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "boolean"
    if isinstance(value, int | float):
        return "number"
    if isinstance(value, str):
        return "string"
    if isinstance(value, list):
        return "array"
    return "object"


def _set(doc: Any, path: Path_, value: object) -> Any:
    out = copy.deepcopy(doc)
    if not path:
        return copy.deepcopy(value)
    cur = out
    for key in path[:-1]:
        cur = cur[key]
    cur[path[-1]] = copy.deepcopy(value)
    return out


def _delete(doc: Any, path: Path_) -> Any:
    out = copy.deepcopy(doc)
    cur = out
    for key in path[:-1]:
        cur = cur[key]
    del cur[path[-1]]
    return out


def _get(doc: Any, path: Path_) -> Any:
    cur = doc
    for key in path:
        cur = cur[key]
    return cur


def _dotted(path: Path_) -> str:
    return ".".join(str(p) for p in path) or "root"


@dataclass(frozen=True, slots=True)
class Mutation:
    """One generated ``schema/`` case before it becomes bytes."""

    id: str
    manifest: object
    expect: Literal["valid", "invalid"]
    why: str


def schema_mutations(schema: dict[str, Any], base: Any = None) -> list[Mutation]:
    """Exercise every keyword of ``schema`` once against ``base``.

    For each node the base manifest reaches:

    - ``type``: one value of a type the node forbids (invalid), and one value
      of each allowed type the base does not already hold (valid).
    - ``enum``: every member the base does not already hold (valid), and one
      non-member (invalid).
    - ``required`` on an object: each name removed in turn (invalid).
      ``required`` on an *array* is ignored by JSON Schema, so it gets no case;
      the lax schema has one, beside ``keyAccess/items``.
    - ``oneOf``: a value matching each branch the base does not (valid).

    The expectation is assigned by construction, not by asking a validator.
    The offline tests then check it against ``jsonschema`` and confirm every
    single-keyword mutant of the schema changes at least one verdict.
    """
    if base is None:
        base = FULL_MANIFEST
    out: list[Mutation] = []

    def emit(kind: str, path: Path_, suffix: str, doc: object, expect: str, why: str):
        tail = f"-{suffix}" if suffix else ""
        out.append(
            Mutation(
                f"schema/{kind}-{_dotted(path)}{tail}",
                doc,
                "valid" if expect == "valid" else "invalid",
                why,
            )
        )

    def walk(node: dict[str, Any], path: Path_) -> None:
        value = _get(base, path)
        if "type" in node:
            allowed = node["type"] if isinstance(node["type"], list) else [node["type"]]
            wrong_name, wrong = next((n, v) for n, v in _WRONG_TYPE if n not in allowed)
            emit(
                "type",
                path,
                wrong_name,
                _set(base, path, wrong),
                "invalid",
                f"{_dotted(path)} must be {'/'.join(allowed)}; given a {wrong_name}",
            )
            for t in allowed:
                if t != _json_type(value) and "enum" not in node:
                    emit(
                        "type",
                        path,
                        t,
                        _set(base, path, _OF_TYPE[t]),
                        "valid",
                        f"{_dotted(path)} may be {t}",
                    )
        if "enum" in node:
            for member in node["enum"]:
                if member != value:
                    emit(
                        "enum",
                        path,
                        _slug(str(member)),
                        _set(base, path, member),
                        "valid",
                        f"{_dotted(path)} may be {member!r}",
                    )
            emit(
                "enum",
                path,
                "non-member",
                _set(base, path, "not-a-member"),
                "invalid",
                f"{_dotted(path)} must be one of {node['enum']}",
            )
        if "required" in node and isinstance(value, dict):
            for name in node["required"]:
                emit(
                    "required",
                    (*path, name),
                    "",
                    _delete(base, (*path, name)),
                    "invalid",
                    f"{_dotted((*path, name))} is required",
                )
        if "oneOf" in node:
            for branch in node["oneOf"]:
                t = branch.get("type")
                if t and t != _json_type(value):
                    emit(
                        "oneof",
                        path,
                        t,
                        _set(base, path, _OF_TYPE[t] if t != "string" else "hash"),
                        "valid",
                        f"{_dotted(path)} may be a {t}",
                    )
                elif t == _json_type(value):
                    walk(branch, path)
        for name, sub in node.get("properties", {}).items():
            if isinstance(value, dict) and name in value:
                walk(sub, (*path, name))
        if "items" in node and isinstance(value, list) and value:
            walk(node["items"], (*path, 0))

    walk(schema, ())
    return out


