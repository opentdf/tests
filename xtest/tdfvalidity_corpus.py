def dumps(manifest: object) -> str:
    """Serialise compactly, the way every SDK writer does."""
    return json.dumps(manifest, separators=(",", ":"), ensure_ascii=False)


def tdf(
    manifest: bytes | str | object,
    *,
    manifest_name: str = MANIFEST,
    payload: bytes | None = PAYLOAD_BYTES,
    **kw: Any,
) -> bytes:
    """A two-entry TDF, payload first as every reference writer orders it."""
    if isinstance(manifest, bytes):
        m = manifest
    elif isinstance(manifest, str):
        m = manifest.encode()
    else:
        m = dumps(manifest).encode()
    entries = [Entry(manifest_name, m)]
    if payload is not None:
        entries.insert(0, Entry(PAYLOAD, payload))
    return zip_bytes(entries, **kw)


def manifest_case(
    id: str, manifest: object, expect: Expect, why: str, **kw: Any
) -> Case:
    """A case that is one manifest in an otherwise unremarkable TDF."""
    text = dumps(manifest)
    if expect == "invalid" and "layer" not in kw:
        kw["layer"] = "manifest-schema"
    return Case(id, tdf(text), expect, why, manifest_text=text, **kw)


