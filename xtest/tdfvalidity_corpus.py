"""The static corpus for the cross-SDK "is this a valid TDF?" suite (DSPX-5349).

Every SDK's ``validate`` command is asked about the same files, so the bytes
are built here, once, in Python -- never by an SDK, and never per SDK. Each
:class:`Case` carries the *agreed* answer; what each SDK actually says lives in
``tdfvalidity_baseline.json`` and is compared by :mod:`tdfvalidity`.

Groups, by what they pin:

- ``control/``: minimal, unremarkable TDFs. If these fail, nothing else means
  anything.
- ``archive/``: ZIP layouts real writers emit (data descriptors, ZIP64), and
  the epic's archive-layer divergences (comment, compression method, sizes).
- ``truncated/``: the control archives cut at every structural boundary.
- ``zip/``: malformed archives -- empty, random, lying offsets and counts.
- ``profile/``: legal ZIP, questionable TDF -- extra, missing, duplicated or
  reordered entries. Undecided until DSPX-4924 settles the container profile.
- ``name/``: which manifest entry a reader picks.
- ``json/``: manifest bytes that are not one clean JSON object.
- ``manifest/``: the 42 lax-schema cases from opentdf/web-sdk#1104.
- ``schema/``: one keyword of the lax schema violated (or exercised) at a
  time, generated by walking ``manifest-lax.schema.json``.
- ``writer/``: realistic manifests in the shape each SDK writes.
- ``golden/``: byte-exact files from Go's unit tests and ``xtest/golden``.
- ``scope/``: payload-level damage no validity API claims to check. Pinned so
  that a validator quietly starting (or stopping) to look is noticed.

The ZIP writer here is deliberately not ``zipfile``: most cases are archives
``zipfile`` refuses to write, and the rest need exact control over every
header field. It is a fixture builder, not a general-purpose writer.
"""

