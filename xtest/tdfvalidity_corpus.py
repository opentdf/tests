def _b64ish(label: str, n: int = 32) -> str:
    """Deterministic base64 text standing in for a key, hash or signature."""
    digest = b""
    counter = 0
    while len(digest) < n:
        digest += hashlib.sha256(f"{label}:{counter}".encode()).digest()
        counter += 1
    return base64.b64encode(digest[:n]).decode()


